#!/usr/bin/env python3
"""Generates the colour variants of the launcher icon (one per accent preset).

Android cannot recolour an app icon at run time, so every colour is a separate icon; the app
switches between them (see AppIcon.kt). Run from the repository root after changing the
drawing in ic_launcher_foreground.xml:  python3 tools/gen_icon_variants.py
"""
import colorsys
import pathlib

RES = pathlib.Path("app/src/main/res")

# name -> (hue in degrees, lightness shift)
VARIANTS = {
    "red": (2, 0.0),
    "orange": (28, 0.02),
    "yellow": (47, 0.06),
    "green": (123, 0.0),
    "cyan": (192, 0.06),
    "blue": (215, 0.0),
    "violet": (285, 0.0),
}

# the parts of the malachite icon: role -> colour
BASE = {
    "gem": "1F7A4D",
    "top": "2E9D63",
    "side": "145236",
    "vein": "7FE0AE",
    "note": "EFFFF6",
    "background": "0B1A12",
}


def shifted(hex_color: str, hue: float, lift: float) -> str:
    r, g, b = (int(hex_color[i:i + 2], 16) / 255 for i in (0, 2, 4))
    _, l, s = colorsys.rgb_to_hls(r, g, b)
    # very light and very dark parts keep their lightness: the note stays white, the background dark
    l2 = l if l > 0.9 or l < 0.1 else min(0.95, l + lift)
    r2, g2, b2 = colorsys.hls_to_rgb(hue / 360, l2, s)
    return "%02X%02X%02X" % (round(r2 * 255), round(g2 * 255), round(b2 * 255))


FOREGROUND = """<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <!-- generated by tools/gen_icon_variants.py: the malachite gem in another colour -->
    <path android:fillColor="#FF{gem}" android:pathData="M54,22 L80,37 L80,71 L54,86 L28,71 L28,37 Z" />
    <path android:fillColor="#FF{top}" android:pathData="M54,22 L80,37 L54,52 L28,37 Z" />
    <path android:fillColor="#FF{side}" android:pathData="M54,52 L80,37 L80,71 L54,86 Z" />
    <path android:strokeColor="#FF{vein}" android:strokeWidth="1.6" android:fillColor="#00000000"
        android:pathData="M36,42 Q54,50 72,42 M34,58 Q54,68 74,58" />
    <path android:fillColor="#FF{note}" android:pathData="M56,36 L56,60.5 C54.9,59.9 53.6,59.5 52.2,59.5 C48.2,59.5 45,62.2 45,65.5 C45,68.8 48.2,71.5 52.2,71.5 C56.2,71.5 59.4,68.8 59.4,65.5 L59.4,45 L66,45 L66,36 Z" />
</vector>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/gen_icon_variants.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_background_{name}" />
    <foreground android:drawable="@drawable/ic_launcher_fg_{name}" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def main() -> None:
    colors = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- generated by tools/gen_icon_variants.py -->", "<resources>"]
    for name, (hue, lift) in VARIANTS.items():
        parts = {role: shifted(value, hue, lift) for role, value in BASE.items()}
        (RES / "drawable" / f"ic_launcher_fg_{name}.xml").write_text(FOREGROUND.format(**parts), encoding="utf-8")
        (RES / "mipmap-anydpi-v26" / f"ic_launcher_{name}.xml").write_text(ADAPTIVE.format(name=name), encoding="utf-8")
        colors.append(f'    <color name="icon_background_{name}">#FF{parts["background"]}</color>')
    colors.append("</resources>")
    (RES / "values" / "icon_colors.xml").write_text("\n".join(colors) + "\n", encoding="utf-8")
    print("icons:", ", ".join(VARIANTS))


if __name__ == "__main__":
    main()
